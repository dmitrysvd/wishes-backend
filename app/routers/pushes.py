from fastapi import APIRouter, Depends, HTTPException, Response
from sqlalchemy.orm import Session
from starlette.status import HTTP_404_NOT_FOUND, HTTP_501_NOT_IMPLEMENTED

from app.dependencies import PUSHES_TAG, get_db
from app.schemas import PushOpenedSchema

router = APIRouter(tags=[PUSHES_TAG])

_OPENED_DESCRIPTION = """\
Сообщить, что приложение открылось по пушу — источник CTR по типу триггера
(фича 0013). Единственная клиентская работа фичи.

**Без `Authorization`.** На холодном старте обработчик пуша срабатывает до
восстановления auth-токена, поэтому ручка публичная: авторизацией служит сам
`delivery_id` — непредсказуемый UUID строки лога отправки, который бэк кладёт в
`data.delivery_id` пуша. Клиент шлёт его сразу при открытии по пушу, не
откладывая до логина. **Условие вызова — наличие `data.delivery_id`** в
открытом пуше, а не `type == price_alert`: когда `delivery_id` появится у других
видов пушей, клиент ничего не меняет. Вызов fire-and-forget: навигацию по
`link` не задерживать, ответа не ждать.

**Что такое «открытие».** Любое действие юзера по пушу: запуск из шторки
(холодный старт или из фона) и тап по тосту в foreground — один и тот же
`delivery_id`. Один best-effort вызов: ошибка сети — молча, без ретраев и без
накопления «непосланных». Хотелка к моменту тапа удалена или в архиве —
открытие всё равно шлите: оно состоялось, карточка покажет своё состояние.
Автоматический показ пуша открытием не считается.

## Пуш по складу — что приходит

Формат как у существующих пушей: `notification` (заголовок/тело рисует ОС в
шторке) **и** `data` (для роутинга и тоста в foreground — `title`/`body` в нём
дублируют `notification`). Единственный пример `data`:

```json
{
  "click_action": "FLUTTER_NOTIFICATION_CLICK",
  "type": "price_alert",
  "delivery_id": "5c1c9a2e-7b1d-4e3a-9f0a-2d6b8c4e1a77",
  "trigger": "price",
  "link": "https://hotelki.pro/wish?wishId=9b2d5e4a-1c3f-4a2b-8d6e-0f1a2b3c4d5e",
  "title": "„Кроссовки для бега“ подешевела",
  "body": "2 700 ₽ вместо 3 000 ₽"
}
```

- `type` — вид пуша, сейчас `price_alert`; клиенту для этой ручки не нужен
  (см. условие вызова выше).
- `trigger` — `price` (подешевело) | `availability` (снова в наличии) |
  `mixed` (дайджест из нескольких хотелок с разными триггерами). Клиенту не
  нужен — бэк знает его по доставке; в `data` лежит для отладки.
- `link` — тот же ключ, что у остальных пушей, открывать через роутер:
  одна хотелка → `{FRONTEND_URL}/wish?wishId=<uuid>`; несколько →
  `{FRONTEND_URL}/` — свой список авторизованного юзера (S2).
- Тексты. Одна хотелка, цена: заголовок `„Название“ подешевела`, тело
  `2 700 ₽ вместо 3 000 ₽`; одна, наличие: `„Название“ снова в наличии`, тело
  `2 700 ₽ на WB`. Несколько: заголовок `3 вещи из списка подешевели или
  вернулись в наличие`, тело — строка первой хотелки (`„Кроссовки для бега“:
  2 700 ₽ вместо 3 000 ₽`). Цены — целые рубли с пробелом-разделителем тысяч.

## Правила фичи (x-push-workflow, самодостаточно)

- **Кому и по каким хотелкам.** Только автору хотелки (не резервировавшим, не
  подписчикам); хотелки активные (не архив), ссылка WB, `price_source = shop`.
  Ручная цена — магазин молчит, пушей нет.
- **Триггер «подешевело».** Цена наблюдения суточного обхода ниже базы «видел»
  на ≥ 10 %. **Отметки просмотра нет**: клиент ничего не шлёт, `GET` карточки/
  списка ничего не двигает. База «видел» = цена со скидкой последнего
  наблюдения с датой ≤ последнего дня активности юзера (`user_activity_day`);
  наблюдений до неё нет — цена хотелки на момент создания; после пуша —
  цена из пуша (что позже). После успешной отправки база = новая цена:
  повторный пуш — только при падении ещё на ≥ 10 % от неё. Рост цены —
  молчим.
- **Триггер «снова в наличии».** Предыдущее наблюдение обхода —
  `sold_out`/`gone`, новое — в наличии с ценой. Один пуш на возврат; ушло и
  вернулось снова — снова пуш. Одиночный запрос кнопкой стартом не считается.
- **Один пуш в календарные сутки UTC** на юзера по складу: все сработавшие за
  обход хотелки — одним сообщением; перезапуск обхода в те же сутки второго
  пуша не даёт. Отправка — в полдень (как остальные крон-пуши), ночных нет.
- **Сброс базы «видел»** — только при успешной отправке (FCM принял); мёртвый
  токен и сбой отправки базу не двигают. Также базу двигают кнопка «актуальная
  с WB» (если принесла цену) и включение группы `prices` (0012: база = текущая
  цена карточки, события при выключенной группе не копятся).
- Хотелка удалена/в архиве между обходом и отправкой — из дайджеста выпадает;
  дайджест опустел — не шлём.

Идемпотентно: первый вызов фиксирует время открытия, повторные (второй тап,
ретрай) — тоже `200`, второе открытие не считается.
"""


@router.post(
    '/push/opened',
    response_class=Response,
    status_code=200,
    description=_OPENED_DESCRIPTION,
    # Публичная ручка: bearer'а на холодном старте ещё нет — снимаем глобальное
    # требование ApiKey.
    openapi_extra={'security': []},
    responses={
        200: {
            'description': (
                'Открытие учтено (или уже было учтено раньше — повтор безвреден). '
                'Тело пустое: клиенту читать нечего.'
            )
        },
        HTTP_404_NOT_FOUND: {
            'description': (
                'Неизвестный `delivery_id`: такой доставки нет (метка испорчена, '
                'либо лог отправок уже почищен). Ничего не записано; клиент '
                'молчит и не ретраит — на UX не влияет.'
            ),
            'content': {'application/json': {'example': {'detail': 'Not Found'}}},
        },
        422: {
            'description': (
                '`delivery_id` — не UUID либо тело пустое. Ничего не записано.'
            )
        },
    },
)
def push_opened(
    body: PushOpenedSchema,
    db: Session = Depends(get_db),
) -> Response:
    """Открытие по пушу — см. `_OPENED_DESCRIPTION`."""
    raise HTTPException(status_code=HTTP_501_NOT_IMPLEMENTED)
