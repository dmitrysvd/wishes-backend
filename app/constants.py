# Прибор возврата (UserActivityDay): ключи в `request.state`, через которые роуты
# сообщают HTTP-мидлвари, что записать. Живут здесь, а не в app.helpers.activity,
# чтобы app.dependencies мог их импортировать без цикла
# (app.helpers → pagination → app.dependencies).
ACTIVITY_STATE_USER_ID = 'activity_user_id'
ACTIVITY_STATE_RADAR_OPENED = 'activity_radar_opened'

# Пагинация
DEFAULT_PAGE_LIMIT = 20
MAX_PAGE_LIMIT = 100

# Реферальная атрибуция: внутренний лимит длины канала установки (utm_source).
# На проводе длина не ограничена — переразмерное значение молча усекается до этого
# лимита (best-effort, без 422). См. фичу 0003 referral-attribution.
UTM_SOURCE_MAX_LENGTH = 64

# ДР из VK со скрытым годом (`DD.MM`): год юзер скрыл, а колонка birth_date — полная
# дата. Храним день+месяц с этим плейсхолдер-годом (ВИСОКОСНЫЙ — чтобы не терять
# 29.02). Год-плейсхолдер значимым наружу не трактуется: всё приложение использует
# только день+месяц ДР (пуши at_noon, публичный вишлист, бёрздей-радар) — год нигде
# не участвует в логике.
VK_HIDDEN_BIRTH_YEAR = 2000

# Загрузка картинок (аватарка, фото хотелки): потолок размера одного файла.
# Честный максимум с клиента — кроп-PNG до 2000×2000 (по проду ≤ 4,5 МБ, p99 1,3 МБ);
# 10 МБ даёт запас ×2, при этом файл читается в память целиком, а у сервера
# ~1 ГБ RAM на всё. В nginx (/api/v1/) лимит чуть выше, чтобы границу отдавало
# приложение JSON-ошибкой, а не nginx HTML-страницей.
UPLOAD_IMAGE_MAX_BYTES = 10 * 1024 * 1024

# Наблюдатель цен (фича 0010): батч артикулов на один запрос к card.wb.ru и пауза
# между батчами. Проверено на проде: 600 артикулов в одном запросе API отдаёт
# без усечения; берём 100, чтобы обход (~2200 позиций → ~22 запроса с паузой)
# не выглядел как выкачка каталога.
PRICE_WATCH_BATCH_SIZE = 100
PRICE_WATCH_BATCH_PAUSE_SECONDS = 3.0


