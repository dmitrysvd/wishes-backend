# ДР из VK со скрытым годом (`DD.MM`): год юзер скрыл, а колонка birth_date — полная
# дата. Храним день+месяц с этим плейсхолдер-годом (ВИСОКОСНЫЙ — чтобы не терять
# 29.02). Год-плейсхолдер значимым наружу не трактуется: всё приложение использует
# только день+месяц ДР (пуши at_noon, публичный вишлист, бёрздей-радар) — год нигде
# не участвует в логике.
VK_HIDDEN_BIRTH_YEAR = 2000

# Загрузка картинок (аватарка, фото хотелки): потолок размера одного файла.
# Честный максимум с клиента — кроп-PNG до 2000×2000 (по проду ≤ 4,5 МБ, p99 1,3 МБ);
# 10 МБ даёт запас ×2, при этом файл читается в память целиком, а у сервера
# ~1 ГБ RAM на всё. В nginx (/api/v1/) лимит чуть выше, чтобы границу отдавало
# приложение JSON-ошибкой, а не nginx HTML-страницей.
UPLOAD_IMAGE_MAX_BYTES = 10 * 1024 * 1024

# Наблюдатель цен (фича 0010): обход размазан по утру UTC — один запрос к
# card.wb.ru на тик, тики раз в TICK_MINUTES в часы HOURS_UTC со случайным сдвигом
# до JITTER_SECONDS. Серия запросов подряд в одно и то же время — то, что антибот
# WB (`server: wbaas`) режет первым; одиночный запрос раз в несколько минут
# выглядит как витрина. Окно кончается до полуденного пуша по складу: хотелка,
# не наблюдённая до него, попадёт в пуш только завтра.
# Ёмкость окна: 11 ч × 12 тиков = 132 тика × BATCH_SIZE = 3300 хотелок; при
# ~2200 целях запас ~45 тиков уходит на повтор упавших батчей. Растёт число
# хотелок — растёт и BATCH_SIZE, иначе хвост не успеет до полудня.
PRICE_WATCH_BATCH_SIZE = 25
PRICE_WATCH_HOURS_UTC = '0-10'
PRICE_WATCH_TICK_MINUTES = 5
# Меньше интервала тика: иначе сдвинутый тик налезет на следующий.
PRICE_WATCH_JITTER_SECONDS = 240
# Свежий запрос цены к магазину из пользовательского запроса (превью, сохранение,
# кнопка «актуальная с WB», фича 0011): бюджет обещан контрактом — не дольше 10 с.
STORE_REQUEST_TIMEOUT_SECONDS = 10.0


