# Общий выключатель пушей по складу (0013). При False крон не считает, не шлёт,
# не пишет лог и не двигает базу «видел» — база начнёт жить с первого включённого
# обхода. Ручка /push/opened и миграции живут независимо от флага.
PRICE_ALERT_ENABLED = True
# Порог триггера «подешевело» (0013): доля от базы «видел». 🟡 дефолт продукта.
PRICE_ALERT_DROP_RATIO = Decimal('0.10')
# Триггер «снова в наличии» выключен решением продукта (dry-run 2026-09-13):
# двухдневная история показала симметричный дневной churn ~4% на sold_out-массе
# (мерцание остатков по размерам у WB), а не возвраты — пуш был бы шумом.
# Включать после накопления истории и дебаунса (N дней подряд без наличия).
# Код триггера, enum и тексты остаются: контракт не меняется.
PRICE_ALERT_AVAILABILITY_ENABLED = False
# Название хотелки в тексте пуша длиннее — обрезается с многоточием: заголовок
# шторки ОС и так усечёт, лучше усечь предсказуемо.
PRICE_ALERT_NAME_MAX_LENGTH = 40

# Пуш «X обновил список желаний» подписчикам. Хотелка попадает в пуш не раньше,
# чем через DELAY после создания: автор накидывает список сессией, и ждём, пока
# она закончится, чтобы одна сессия ушла одним пушем, а не по хотелке в час.
WISH_CREATION_PUSH_DELAY = timedelta(hours=3)
# Одному подписчику про одного автора — не чаще раза в сутки (по логу
# отправок). Хотелки, добавленные автором в этот интервал, для такого
# подписчика в пуш не попадут вовсе: он уже знает, что список обновился.
WISH_CREATION_PUSH_MIN_INTERVAL = timedelta(hours=24)
# Часы UTC, в которые крон вообще шлёт эти пуши; вне окна хотелки копятся
# и уходят первым прогоном внутри окна. 6–17 UTC = 9–20 МСК: не будить ночью.
WISH_CREATION_PUSH_HOURS_UTC = range(6, 18)


